import heapq

graph = {
    "S": [("A", 1), ("B", 4)],
    "A": [("C", 2)],
    "B": [("G", 5)],
    "C": [("G", 3)],
    "G": []
}

heuristic = {
    "S": 5,
    "A": 4,
    "B": 4,
    "C": 2,
    "G": 0
}

def astar(graph, h, start, goal):
    pq = [(h[start], 0, start, [start])]
    best = {start: 0}
    processed = []
    expanded = []

    while pq:
        f, g, node, path = heapq.heappop(pq)

        if g != best[node]:
            continue

        processed.append(node)

        if node == goal:
            return g, path, processed, expanded

        expanded.append(node)

        for nxt, w in graph.get(node, []):
            new_g = g + w

            if new_g < best.get(nxt, float("inf")):
                best[nxt] = new_g
                heapq.heappush(
                    pq, (new_g + h[nxt],
                         new_g, nxt, path + [nxt])
                )

    return float("inf"), [], processed, expanded

# A* using the supplied heuristic
print("A* Result:")
print(astar(graph, heuristic, "S", "G"))

# UCS uses zero heuristic
zero_h = {node: 0 for node in graph}

print("UCS Result:")
print(astar(graph, zero_h, "S", "G"))


modified_h = heuristic.copy()
modified_h["C"] = 10

print("A* with Overestimated Heuristic:")
print(astar(graph, modified_h, "S", "G"))