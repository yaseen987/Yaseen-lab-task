import math

scores = [3, 5, 2, 9, 3, 5, 2, 9]
depth = int(math.log2(len(scores)))


def minimax(node, level, maximizing, count):
    if level == depth:
        count[0] += 1
        return scores[node]

    if maximizing:
        best = float("-inf")

        for i in range(2):
            value = minimax(
                2 * node + i, level + 1, False, count
            )
            best = max(best, value)

        return best

    else:
        best = float("inf")

        for i in range(2):
            value = minimax(
                2 * node + i, level + 1, True, count
            )
            best = min(best, value)

        return best


def alpha_beta(node, level, maximizing, alpha, beta, count):
    if level == depth:
        count[0] += 1
        return scores[node]

    if maximizing:
        best = float("-inf")

        for i in range(2):
            value = alpha_beta(
                2 * node + i, level + 1,
                False, alpha, beta, count
            )
            best = max(best, value)
            alpha = max(alpha, best)

            if beta <= alpha:
                break

        return best

    else:
        best = float("inf")

        for i in range(2):
            value = alpha_beta(
                2 * node + i, level + 1,
                True, alpha, beta, count
            )
            best = min(best, value)
            beta = min(beta, best)

            if beta <= alpha:
                break

        return best


minimax_count = [0]
minimax_value = minimax(0, 0, True, minimax_count)

alpha_beta_count = [0]
alpha_beta_value = alpha_beta(
    0, 0, True, float("-inf"), float("inf"), alpha_beta_count
)

print("Minimax Value:", minimax_value)
print("Minimax Leaves Evaluated:", minimax_count[0])

print("Alpha-Beta Value:", alpha_beta_value)
print("Alpha-Beta Leaves Evaluated:", alpha_beta_count[0])