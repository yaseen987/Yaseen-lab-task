import re

samples = [
    "AI, search!",
    "I can't log in.",
    "help@example.com",
    "CS4944 version 2.1",
    "",
    "یہ ایک مثال ہے"
]

print("TOKENIZATION COMPARISON")
print("=" * 70)

for text in samples:
    whitespace = text.split()
    word_like = re.findall(r"\b\w+\b", text, flags=re.UNICODE)

    print("Original:", repr(text))
    print("Whitespace:", whitespace, "Count:", len(whitespace))
    print("Word-like:", word_like, "Count:", len(word_like))
    print("-" * 70)

try:
    from sentence_transformers import SentenceTransformer

    model = SentenceTransformer(
        "sentence-transformers/all-MiniLM-L6-v2",
        device="cpu"
    )

    print("\nMODEL SUBWORD TOKENS")

    for text in samples[:2]:
        print("Original:", repr(text))
        print("Model tokens:", model.tokenizer.tokenize(text))

except Exception as e:
    print("\nModel tokenizer unavailable:", type(e).__name__)
    print("Install sentence-transformers and run again.")

print("\nEXPLANATION")

print("1. Whitespace splitting keeps punctuation attached to words,")
print("   while the word-like regex removes punctuation and can")
print("   split contractions.")

print("2. The model tokenizer uses subword units, so its token count")
print("   can differ from both whitespace and word-like counts.")

print("Normalization risk: aggressive normalization can change or")
print("remove negation, identifiers, punctuation, or other information")
print("needed for retrieval.")