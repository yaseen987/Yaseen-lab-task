from sklearn.feature_extraction.text import TfidfVectorizer

FAQ = [
    {
        "id": "faq:password",
        "question": "How do I reset my password?",
        "answer": "Use the recovery link on the login page.",
        "source": "it_help.txt"
    },
    {
        "id": "faq:submit",
        "question": "Where do I submit my assignment?",
        "answer": "Use the assignment upload page in the learning portal.",
        "source": "assessment.txt"
    },
    {
        "id": "faq:late",
        "question": "Can illness justify a late submission?",
        "answer": "Request an extension with medical evidence before the deadline.",
        "source": "handbook.txt"
    },
    {
        "id": "faq:broken",
        "question": "What should I do if my parcel arrives broken?",
        "answer": "Contact support within 48 hours and attach photographs of the item and packaging.",
        "source": "returns_guide.txt"
    },
    {
        "id": "faq:remote",
        "question": "Can contractors work remotely?",
        "answer": "Contractors may work remotely only when the signed contract explicitly permits it.",
        "source": "hr_policy.txt"
    }
]


# Create text for TF-IDF
texts = [item["question"] + " " + item["answer"] for item in FAQ]

vectorizer = TfidfVectorizer()
matrix = vectorizer.fit_transform(texts)


def reply(query):

    if not query.strip():
        return "Please enter a question."

    # Exact FAQ match
    for item in FAQ:
        if query.strip().casefold() == item["question"].casefold():
            return (
                item["answer"]
                + " [source: "
                + item["source"]
                + "]"
            )

    # TF-IDF search
    query_vector = vectorizer.transform([query])

    if query_vector.nnz == 0:
        return "No matching FAQ. Please contact the help desk."

    scores = (query_vector @ matrix.T).toarray()[0]

    ranked = scores.argsort()[::-1]

    # If there is no lexical match
    if scores[ranked[0]] <= 0:
        return "No matching FAQ. Please contact the help desk."

    result = [
        "Possible matches; choose or rephrase your question:"
    ]

    for i in ranked[:3]:
        if scores[i] > 0:
            result.append(
                FAQ[i]["question"]
                + f" (similarity {scores[i]:.3f})"
            )

    return "\n".join(result)


