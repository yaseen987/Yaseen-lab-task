def scholarship_decision(score, documents_complete,
                         residency_verified, income_eligible):
    if (score >= 70
            and documents_complete
            and residency_verified
            and income_eligible):
        return "Review"
    else:
        return "Hold"


# Exactly four test cases
test_cases = [
    {
        "name": "Pass",
        "input": {
            "score": 85,
            "documents_complete": True,
            "residency_verified": True,
            "income_eligible": True
        },
        "expected": "Review"
    },
    {
        "name": "Residency condition failure",
        "input": {
            "score": 85,
            "documents_complete": True,
            "residency_verified": False,
            "income_eligible": True
        },
        "expected": "Hold"
    },
    {
        "name": "Income condition failure",
        "input": {
            "score": 85,
            "documents_complete": True,
            "residency_verified": True,
            "income_eligible": False
        },
        "expected": "Hold"
    },
    {
        "name": "Threshold boundary",
        "input": {
            "score": 70,
            "documents_complete": True,
            "residency_verified": True,
            "income_eligible": True
        },
        "expected": "Review"
    }
]


# Run and print the test cases
for case in test_cases:
    data = case["input"]

    actual = scholarship_decision(
        data["score"],
        data["documents_complete"],
        data["residency_verified"],
        data["income_eligible"]
    )

    print("Test Case:", case["name"])
    print("Input:", data)
    print("Expected:", case["expected"])
    print("Actual:", actual)
    print("Passed:", actual == case["expected"])
    print("-" * 50)