import math

def minimax(depth, index, maxTurn, scores, targetDepth, counter):
    if depth == targetDepth:
        counter[0] += 1
        return scores[index]

    if maxTurn:
        return max(
            minimax(depth + 1, index * 2, False, scores, targetDepth, counter),
            minimax(depth + 1, index * 2 + 1, False, scores, targetDepth, counter)
        )
    else:
        return min(
            minimax(depth + 1, index * 2, True, scores, targetDepth, counter),
            minimax(depth + 1, index * 2 + 1, True, scores, targetDepth, counter)
        )


def alphabeta(depth, index, maxTurn, scores, targetDepth, alpha, beta, counter):
    if depth == targetDepth:
        counter[0] += 1
        return scores[index]

    if maxTurn:
        value = float('-inf')

        for i in range(2):
            value = max(
                value,
                alphabeta(depth + 1, index * 2 + i, False,
                          scores, targetDepth, alpha, beta, counter)
            )
            alpha = max(alpha, value)

            if alpha >= beta:
                break

        return value

    else:
        value = float('inf')

        for i in range(2):
            value = min(
                value,
                alphabeta(depth + 1, index * 2 + i, True,
                          scores, targetDepth, alpha, beta, counter)
            )
            beta = min(beta, value)

            if alpha >= beta:
                break

        return value


# Original scores
original = [3, 5, 2, 9, 3, 5, 2, 9]

# Reordered scores
reordered = [9, 2, 5, 3, 9, 2, 5, 3]

depth = int(math.log2(len(original)))

# Original tree
minimax_count1 = [0]
alphabeta_count1 = [0]

minimax_value1 = minimax(
    0, 0, True, original, depth, minimax_count1
)

alphabeta_value1 = alphabeta(
    0, 0, True, original, depth,
    float('-inf'), float('inf'), alphabeta_count1
)

# Reordered tree
minimax_count2 = [0]
alphabeta_count2 = [0]

minimax_value2 = minimax(
    0, 0, True, reordered, depth, minimax_count2
)

alphabeta_value2 = alphabeta(
    0, 0, True, reordered, depth,
    float('-inf'), float('inf'), alphabeta_count2
)

print("Original Scores:", original)
print("Minimax Value:", minimax_value1)
print("Minimax Evaluated Leaves:", minimax_count1[0])
print("Alpha-Beta Value:", alphabeta_value1)
print("Alpha-Beta Evaluated Leaves:", alphabeta_count1[0])

print("\nReordered Scores:", reordered)
